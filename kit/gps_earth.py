TEX, CLOUD, LIGHTS, LANDM = build_texture()


def ray_dirs(c, x0, y0, x1, y1):
    py, px = np.mgrid[y0:y1, x0:x1].astype(np.float64)
    sx = (px + 0.5) / S
    sy = (py + 0.5) / S
    dx = sx - 540.0
    dy = c['cy'] - sy
    dz = np.full_like(dx, FOC)
    cp, sp, ca, sa = c['cp'], c['sp'], c['ca'], c['sa']
    yw = dy * cp - dz * sp
    z1 = dy * sp + dz * cp
    xw = dx * ca - z1 * sa
    zw = dx * sa + z1 * ca
    n = np.sqrt(xw * xw + yw * yw + zw * zw)
    return xw / n, yw / n, zw / n


def surf_point(ctr, R, lat, lon, spin_deg, tilt_deg=0.0, h=0.0):
    """punto del mundo sobre la superficie (para etiquetas)"""
    la, lo = math.radians(lat), math.radians(lon - spin_deg)
    n = np.array([math.cos(la) * math.sin(lo), math.sin(la), -math.cos(la) * math.cos(lo)])
    b = math.radians(tilt_deg)
    Rx = np.array([[1, 0, 0], [0, math.cos(b), -math.sin(b)], [0, math.sin(b), math.cos(b)]])
    n = Rx @ n
    return tuple(np.asarray(ctr, np.float64) + (R + h) * n)


def _bil(T, fx, fy):
    """muestreo bilineal (x cíclico, y acotado)"""
    h, w = T.shape[0], T.shape[1]
    x0 = np.floor(fx).astype(np.int32)
    y0 = np.clip(np.floor(fy).astype(np.int32), 0, h - 2)
    wx = (fx - x0).astype(np.float32)
    wy = np.clip(fy - y0, 0, 1).astype(np.float32)
    x0 %= w
    x1 = (x0 + 1) % w
    if T.ndim == 3:
        wx, wy = wx[..., None], wy[..., None]
    return (T[y0, x0] * (1 - wx) * (1 - wy) + T[y0, x1] * wx * (1 - wy) + T[y0 + 1, x0] * (1 - wx) * wy + T[y0 + 1, x1] * wx * wy)


def render_earth(arr, c, ctr, R, spin_deg, sun, atmo=1.0, lights_k=1.0, cloud_spin=0.0, bright=1.0, tilt_deg=0.0, smooth=False):
    """Compone la Tierra sobre arr (H,W,3 float32). Devuelve máscara de cobertura (H,W) para oclusión."""
    from nc import proj
    sx, sy, dep = proj(*ctr, c)
    mask_full = np.zeros((H, W), np.float32)
    if dep <= 0 and math.dist(c['pos'], ctr) > R:
        return mask_full
    if dep > R * 1.3:
        rp = R * 1.18 * FOC / math.sqrt(max(1.0, dep * dep - R * R)) * S
        x0, x1 = int(max(0, sx * S - rp - 4)), int(min(W, sx * S + rp + 4))
        y0, y1 = int(max(0, sy * S - rp - 4)), int(min(H, sy * S + rp + 4))
    else:
        x0, y0, x1, y1 = 0, 0, W, H
    if x1 <= x0 or y1 <= y0:
        return mask_full
    dx, dy, dz = ray_dirs(c, x0, y0, x1, y1)
    ox, oy, oz = (c['pos'][0] - ctr[0], c['pos'][1] - ctr[1], c['pos'][2] - ctr[2])
    b = ox * dx + oy * dy + oz * dz
    cc = ox * ox + oy * oy + oz * oz - R * R
    disc = b * b - cc
    hit = disc > 0
    tt = -b - np.sqrt(np.maximum(disc, 0))
    hit &= tt > 0
    # distancia mínima del rayo al centro (para el halo)
    tmin = np.maximum(-b, 0)
    qx, qy, qz = ox + tmin * dx, oy + tmin * dy, oz + tmin * dz
    dmin = np.sqrt(qx * qx + qy * qy + qz * qz)
    sun = np.array(sun, np.float64)
    sun /= np.linalg.norm(sun)
    out = arr[y0:y1, x0:x1]
    # halo de atmósfera
    hw = 0.055 * R
    ring = np.clip(1 - (dmin - R) / hw, 0, 1) * (dmin > R)
    ring = ring ** 2.2
    qn = np.stack([qx, qy, qz], -1) / np.maximum(dmin, 1e-9)[..., None]
    day_r = np.clip(0.25 + 0.9 * (qn @ sun), 0, 1)
    halo = (ring * day_r * atmo)[..., None] * np.array([70, 140, 255], np.float32)
    out += halo.astype(np.float32) * (~hit)[..., None]
    if hit.any():
        px_, py_, pz_ = ox + tt * dx, oy + tt * dy, oz + tt * dz
        nx, ny, nz = px_ / R, py_ / R, pz_ / R
        if tilt_deg:
            b = math.radians(tilt_deg)
            cb, sb = math.cos(b), math.sin(b)
            tny = ny * cb + nz * sb
            tnz = -ny * sb + nz * cb
            tnx = nx
        else:
            tnx, tny, tnz = nx, ny, nz
        lat = np.degrees(np.arcsin(np.clip(tny, -1, 1)))
        lon = np.degrees(np.arctan2(tnx, -tnz)) + spin_deg
        lon = (lon + 180.0) % 360.0 - 180.0
        if smooth:
            fx = (lon + 180.0) / 360.0 * TW - 0.5
            fy = (90.0 - lat) / 180.0 * TH - 0.5
            alb = _bil(TEX, fx, fy)
            cl = _bil(CLOUD, fx + cloud_spin / 360.0 * TW, fy)[..., None]
            lmask = _bil(LANDM, fx, fy)
            g = (0.5 + 0.5 * np.sin(lon * 23.0 + 2.0 * np.sin(lat * 17.0))) * (0.5 + 0.5 * np.sin(lat * 29.0 + 1.7 * np.sin(lon * 13.0)))
            g = np.clip(g * 1.8 - 0.25, 0, 1.4)
            lts = _bil(LIGHTS, fx, fy) * g
        else:
            tx = ((lon + 180.0) / 360.0 * TW).astype(np.int32) % TW
            ty = np.clip(((90.0 - lat) / 180.0 * TH).astype(np.int32), 0, TH - 1)
            alb = TEX[ty, tx]
            txc = ((tx + int(cloud_spin / 360.0 * TW)) % TW)
            cl = CLOUD[ty, txc][..., None]
            lmask = LANDM[ty, tx]
            lts = LIGHTS[ty, tx]
        lam = nx * sun[0] + ny * sun[1] + nz * sun[2]
        dif = np.clip(lam, 0, 1)[..., None]
        twi = np.clip((lam + 0.12) / 0.24, 0, 1)[..., None]
        col = alb * (0.06 + 1.05 * dif)
        col = col + (np.array([235, 240, 250], np.float32) * (0.05 + 1.0 * dif) - col) * cl * 0.85
        # brillo especular en el océano
        vx, vy, vz = -dx, -dy, -dz
        hx, hy, hz = vx + sun[0], vy + sun[1], vz + sun[2]
        hn = np.sqrt(hx * hx + hy * hy + hz * hz)
        spec = np.clip((nx * hx + ny * hy + nz * hz) / hn, 0, 1) ** 60
        oc = (1 - lmask)[..., None] * (1 - cl)
        col = col + spec[..., None] * oc * np.array([200, 210, 230], np.float32) * 0.6
        # luces nocturnas
        lt = lts[..., None] * (1 - twi) * (1 - cl * 0.8) * lights_k
        col = col + lt * np.array([255, 196, 110], np.float32)
        # borde atmosférico
        fres = np.clip(1 - (nx * vx + ny * vy + nz * vz), 0, 1) ** 3
        col = col + (fres * atmo * (0.15 + 0.85 * twi[..., 0]))[..., None] * np.array([60, 120, 255], np.float32)
        # suavizado del borde (antialias simple)
        edge = np.clip(np.sqrt(np.maximum(disc, 0)) / (R * 0.012), 0, 1)[..., None]
        col = col * bright
        out[...] = out * (1 - hit[..., None] * edge) + col * hit[..., None] * edge
        mask_full[y0:y1, x0:x1] = hit.astype(np.float32)
    arr[y0:y1, x0:x1] = out
    return mask_full


def occluded(c, p, ctr, R):
    """True si el punto p queda oculto detrás de la esfera (ctr, R) vista desde la cámara."""
    o = np.array(c['pos'], np.float64)
    d = np.array(p, np.float64) - o
    L = np.linalg.norm(d)
    if L < 1e-9:
        return False
    d /= L
    oc = o - np.array(ctr, np.float64)
    b = oc @ d
    cc = oc @ oc - R * R
    disc = b * b - cc
    if disc <= 0:
        return False
    t0 = -b - math.sqrt(disc)
    return 0 < t0 < L
