def _xy(lon, lat):
    return ((lon + 180.0) / 360.0 * TW, (90.0 - lat) / 180.0 * TH)


def _noise(lon, lat, seed, octaves=4):
    rs = np.random.RandomState(seed)
    la, lo = np.radians(lat), np.radians(lon)
    x, y, z = np.cos(la) * np.cos(lo), np.sin(la), np.cos(la) * np.sin(lo)
    out = np.zeros_like(x)
    amp, fr = 1.0, 2.0
    for _ in range(octaves):
        for _k in range(3):
            a = rs.normal(size=3)
            a /= np.linalg.norm(a)
            ph = rs.uniform(0, 6.28)
            out += amp * np.sin(fr * (a[0] * x + a[1] * y + a[2] * z) * 3.0 + ph)
        amp *= 0.5
        fr *= 2.1
    return out


